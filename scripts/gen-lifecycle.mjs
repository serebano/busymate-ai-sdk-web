#!/usr/bin/env node
// Generates src/lifecycle.gen.ts from the Busymate identity contract (busymate-ai-src
// packages/identity-contract/src/lifecycle.ts). Never hand-edit the output.
//   node scripts/gen-lifecycle.mjs <path-to-lifecycle.ts>        write src/lifecycle.gen.ts
//   node scripts/gen-lifecycle.mjs <path-to-lifecycle.ts> --check  fail when the committed file differs
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const [, , source, flag] = process.argv;
if (!source) {
  console.error("usage: gen-lifecycle.mjs <lifecycle.ts> [--check]");
  process.exit(2);
}
const text = readFileSync(source, "utf8");
const block = (name) => {
  const m = text.match(new RegExp(`export const ${name}[^=]*=\\s*\\[([\\s\\S]*?)\\n\\];`));
  if (!m) throw new Error(`lifecycle.ts: ${name} not found`);
  return m[1];
};
const web = [...block("WEB_LIFECYCLE").matchAll(/name:\s*"([A-Za-z]+)\(/g)].map((m) => m[1]);
const aliases = [...block("LIFECYCLE_ALIASES").matchAll(/alias:\s*"([A-Za-z*]+)(?:\(([^)]*)\))?",\s*of:\s*"([A-Za-z ]+)"/g)].map((m) => ({
  alias: m[1],
  arg: m[2] ?? "",
  of: m[3],
}));
const desktop = text.match(/DESKTOP_CHANNEL\s*=\s*"([a-z_]+)"/)?.[1];
const forbidden = text.match(/FORBIDDEN_DESKTOP_CHANNEL\s*=\s*"([a-z_]+)"/)?.[1];
if (web.length !== 4 || !desktop || !forbidden) throw new Error("lifecycle.ts: unexpected shape");

const hash = createHash("sha256").update(text).digest("hex");
const out = `// GENERATED by scripts/gen-lifecycle.mjs from busymate-ai-src packages/identity-contract/src/lifecycle.ts
// (sha256 ${hash}). Do not hand-edit: change the contract, then regenerate.

/** The canonical web lifecycle calls, in contract order. */
export const WEB_LIFECYCLE_NAMES = ${JSON.stringify(web)} as const;

/** Accepted but never documented spellings, and the canonical call each maps to. */
export const WEB_LIFECYCLE_ALIASES = ${JSON.stringify(aliases.filter((a) => /^[a-z][A-Za-z]+$/.test(a.alias)), null, 2)} as const;

/** Desktop SDKs use this channel; the other spelling is refused. */
export const DESKTOP_CHANNEL = ${JSON.stringify(desktop)};
export const FORBIDDEN_DESKTOP_CHANNEL = ${JSON.stringify(forbidden)};
`;
const target = fileURLToPath(new URL("../src/lifecycle.gen.ts", import.meta.url));
if (flag === "--check") {
  if (readFileSync(target, "utf8") !== out) {
    console.error("src/lifecycle.gen.ts is stale: regenerate it from the contract");
    process.exit(1);
  }
  console.log("lifecycle.gen.ts matches the contract");
} else {
  writeFileSync(target, out);
  console.log("wrote src/lifecycle.gen.ts");
}
